/**
 * Storage facade.
 *
 * Views call `db.*` and never touch an adapter directly. Swapping a detachment
 * from local storage to Google Drive is therefore a setup-screen change, not a
 * code change.
 *
 * Record layout inside the detachment's folder:
 *   config/org.json                          detachment profile, schema version
 *   config/settings.json                     shared settings
 *   users/users.json                         the roster
 *   forms/<formId>.json                      form templates
 *   requests/<requestId>.json                requests in the shared space
 *   responses/<requestId>/<responseId>.json  submitted feedback
 *   receipts/<requestId>/<username>.json     who has answered, one file each
 *   audit/<YYYY-MM>.json                     the activity log, by month
 *   cadre/…, commander/…                     the same requests/responses shape,
 *                                            one subtree per restricted space
 *   archive/, reports/                       exports and retired terms
 *
 * `roster/students.json` is the pre-v4 roster. New folders no longer get one;
 * it is read only where a migration finds it. The live roster is users/.
 */

