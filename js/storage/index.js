/**
 * Local, because importing auth.js here would close a cycle — not directly,
 * as the old wording claimed, but through auth -> audit -> this module.
 * Kept in step with `suggestUsername` in auth.js by hand; they must agree,
 * because a username generated by one is filed against receipts read by the
 * other.
 */
function suggestUsername(name, taken = []) {
  const parts = String(name || '').replace(/,/g, ' ').trim().split(/\s+/).filter(Boolean);
  const last = parts.length > 1 ? parts[0] : (parts[0] || 'cadet');
  const first = parts.length > 1 ? parts[1] : '';
  let base = `${last}${first ? `.${first}` : ''}`.toLowerCase().replace(/[^a-z0-9._-]/g, '');
  if (base.length < 3) base = `${base}user`;
  const existing = new Set(taken);
  if (!existing.has(base)) return base;
  for (let n = 2; n < 999; n++) if (!existing.has(`${base}${n}`)) return `${base}${n}`;
  return `${base}${Date.now().toString(36)}`;
}

